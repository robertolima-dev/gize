pub fn validate_identifier(name: &str, kind: &str) -> Result<()> {
    ensure!(
        name != "_"
            && !name.is_empty()
            && name
                .bytes()
                .next()
                .is_some_and(|b| b.is_ascii_lowercase() || b == b'_')
            && name
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'),
        "invalid {kind} `{name}`: use a lowercase ASCII snake_case identifier, starting with a letter or underscore"
    );
    ensure!(
        name.len() <= 63,
        "invalid {kind} `{name}`: maximum identifier length is 63 bytes"
    );
    ensure!(
        !RUST_KEYWORDS.contains(&name),
        "invalid {kind} `{name}`: reserved Rust keyword"
    );
    Ok(())
}

/// Check unquoted SQL names only when the target database is known.
pub fn validate_sql_identifier_for_dialect(
    name: &str,
    kind: &str,
    dialect: crate::Dialect,
) -> Result<()> {
    validate_identifier(name, kind)?;
    let reserved = match dialect {
        crate::Dialect::Postgres => POSTGRES_RESERVED,
        crate::Dialect::Sqlite => SQLITE_RESERVED,
        crate::Dialect::MySql => MYSQL_RESERVED,
    };
    ensure!(
        !reserved.contains(&name),
        "invalid {kind} `{name}`: reserved SQL keyword for {dialect:?}; choose another name"
    );
    Ok(())
}

pub fn validate_column(name: &str) -> Result<()> {
    validate_identifier(name, "field")?;
    ensure!(
        !["id", "created_at", "updated_at"].contains(&name),
        "invalid field `{name}`: automatically generated by Gize"
    );
    Ok(())
}

pub fn validate_model_name(name: &str) -> Result<()> {
    ensure!(
        !RUST_KEYWORDS.contains(&name),
        "invalid model `{name}`: reserved Rust keyword"
    );
    ensure!(
        name.bytes().next().is_some_and(|b| b.is_ascii_uppercase())
            && name.bytes().all(|b| b.is_ascii_alphanumeric()),
        "invalid model `{name}`: use an ASCII PascalCase name, such as BlogPost"
    );
    ensure!(
        ![
            "String",
            "Vec",
            "Result",
            "Error",
            "State",
            "AppState",
            "StatusCode",
            "Json",
            "Serialize",
            "Deserialize"
        ]
        .contains(&name),
        "invalid model `{name}`: conflicts with a type used by generated code"
    );
    validate_identifier(&crate::naming::table_name(name), "generated table")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Dialect;

    #[test]
    fn reserved_words_follow_the_selected_database() {
        // Each rejected word was confirmed to break generated SQL on a real server.
        for (dialect, rejected, accepted) in [
            (
                Dialect::Postgres,
                &[
                    "array", "only", "cast", "analyze", "binary", "user", "order",
                ][..],
                &["key", "index", "database", "values", "rows", "range"][..],
            ),
            (
                Dialect::MySql,
                &[
                    "range", "interval", "schema", "read", "lock", "show", "rank", "rows",
                ][..],
                &["user", "returning", "offset", "array", "only"][..],
            ),
            (
                Dialect::Sqlite,
                &["index", "values", "order", "transaction", "commit"][..],
                &["key", "database", "user", "rows", "range", "offset"][..],
            ),
        ] {
            for name in rejected {
                let error = validate_sql_identifier_for_dialect(name, "field", dialect)
                    .unwrap_err()
                    .to_string();
                assert!(
                    error.contains("reserved SQL keyword"),
                    "{dialect:?}: {error}"
                );
            }
            for name in accepted {
                validate_sql_identifier_for_dialect(name, "field", dialect)
                    .unwrap_or_else(|e| panic!("{dialect:?}: {e}"));
            }
        }
    }

    #[test]
    fn reserved_lists_are_sorted_lowercase_identifiers() {
        for list in [POSTGRES_RESERVED, SQLITE_RESERVED, MYSQL_RESERVED] {
            assert!(list.windows(2).all(|w| w[0] < w[1]));
            assert!(list.iter().all(|w| validate_identifier(w, "keyword").is_ok()
                || RUST_KEYWORDS.contains(w)));
        }
    }
}
